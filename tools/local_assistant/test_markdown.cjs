const assert=require('node:assert/strict');
global.katex=require('./assets/katex/katex.min.js');
const {render}=require('./assets/markdown.js');
assert.match(render('# 标题\n\n- 第一项\n- 第二项\n\n> 引用'),/<h2>标题<\/h2>/);
assert.match(render('- 第一项\n  - 子项\n- 第二项'),/<ul>[\s\S]*<ul>/);
assert.match(render('1. 清洗\n2. 统计'),/<ol start="1">/);
assert.match(render('> 提醒'),/<blockquote>/);
assert.match(render('| A | B |\n|---|---|\n| `a|b` | c |'),/<code>a\|b<\/code>/);
assert.match(render('```python\nprint("<script>")\n```'),/&lt;script&gt;/);
assert.doesNotMatch(render('<img src=x onerror=alert(1)>'),/<img/);
assert.doesNotMatch(render('[点我](javascript:alert(1))'),/href=/);
assert.match(render('[链接](https://example.com/a**b**c)'),/href="https:\/\/example.com\/a\*\*b\*\*c"/);
assert.match(render('平均值 \\(\\frac{1}{n}\\sum_i x_i\\) 。'),/class="katex"/);
assert.match(render('$$x^2+y^2=z^2$$'),/katex-display/);
assert.doesNotMatch(render('`\\(x^2\\)`'),/class="katex"/);
assert.match(render('\\(\\href{javascript:alert}{x}\\)'),/katex/);
assert.doesNotMatch(render('\\(\\href{javascript:alert}{x}\\)'),/href="javascript/);
assert.match(render('```\n未结束的代码\n'),/<pre>未结束的代码/);
console.log('Markdown checks passed: lists, quotes, code, tables, local math, unclosed fences, and inert HTML/links.');
